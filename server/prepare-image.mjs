import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

// Paseo bundles server code into an evaluated string. Native modules must stay in node_modules,
// with an absolute entry resolved on this daemon rather than relative to Paseo's evaluator.
const require = createRequire(import.meta.url);
const file = new URL("./sharp-path.ts", import.meta.url);
const source = `// Generated by prepare-image.mjs for this installation.\nexport const sharpPath = ${JSON.stringify(require.resolve("sharp"))};\n`;
let current;
try {
  current = readFileSync(file, "utf8");
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}
if (source !== current) writeFileSync(file, source);
